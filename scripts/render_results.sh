#!/usr/bin/env bash
# Render the newest results/*-<cc>.json for each compiler into results.md.
# Usage: scripts/render_results.sh
set -euo pipefail
cd "$(dirname "$0")/.."

{
    echo "# fastparse results"
    echo
    echo "Generated by \`scripts/render_results.sh\` from \`results/\`. Throughput mode unless noted;"
    echo "TSC ticks equal core cycles with boost off. Lower is better except Mnum/s and MB/s."
    for cc in gcc clang; do
        f=$(find results -name "*-$cc.json" | sort | tail -1)
        [ -n "$f" ] || continue
        echo
        jq -r '"## \(.compiler)\n\n\(.cpu), kernel \(.kernel), `\(.build | sub("^built with "; ""))`, core \(.core), governor \(.governor), boost \(.boost), \(.reps) reps. Run \(.date) (`'"$f"'`).\n",
            "| parser | corpus | mode | Mnum/s | MB/s | TSC/num p50 | p99 | p99.9 | instr/num | br-miss/num |",
            "|---|---|---|--:|--:|--:|--:|--:|--:|--:|",
            (.runs[] | "| \(.parser) | \(.corpus) | \(.mode) | \(.mnum_per_s) | \(.mb_per_s) | \(.tsc_per_num.p50) | \(.tsc_per_num.p99) | \(.tsc_per_num.p999) | \(.perf.instructions // "-") | \(.perf.branch_misses // "-") |")' "$f"
    done
} >results.md
echo "results.md"
